#!/usr/bin/env python3
"""Export the plugin element vocabulary to the SPA's generated TypeScript module.

nexuusbot.plugins.vocabulary owns the ten element kinds, their direction and
tone words, and the caps both surfaces enforce. This script renders that
ownership into frontend/src/plugins/vocabulary.generated.ts; the committed
copy is checked by tests/test_vocabulary_export.py, which re-runs the exporter
and fails when the two have drifted.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))

from nexuusbot.plugins import vocabulary  # noqa: E402

DEFAULT_OUT = REPO_ROOT / "frontend" / "src" / "plugins" / "vocabulary.generated.ts"


def render_typescript() -> str:
    """Return the generated module's exact text, ending in one newline.

    The kind and word tuples render one entry per line so a changed kind
    shows up as a reviewable diff, and the caps render as literals the SPA
    can compare against without importing the Python module.
    """
    kinds = "\n".join(f'  "{kind}",' for kind in vocabulary.ELEMENT_KINDS)
    directions = ", ".join(f'"{word}"' for word in vocabulary.DIRECTIONS)
    tones = ", ".join(f'"{word}"' for word in vocabulary.TONES)
    row_caps = ", ".join(
        f"{kind}: {cap}" for kind, cap in vocabulary.ROW_CAPS.items()
    )
    return f"""// Generated by scripts/export_plugin_vocabulary.py from
// src/nexuusbot/plugins/vocabulary.py. Do not edit this file by hand: edit the
// Python module and re-run the exporter so both surfaces own one vocabulary.
export const ELEMENT_KINDS = [
{kinds}
] as const;

export type ElementKind = (typeof ELEMENT_KINDS)[number];

export const DIRECTIONS = [{directions}] as const;

export const TONES = [{tones}] as const;

export const ROW_CAPS: Readonly<Record<string, number>> = {{ {row_caps} }};

export const SPARKLINE_MIN_POINTS = {vocabulary.SPARKLINE_MIN_POINTS};

export const SPARKLINE_MAX_POINTS = {vocabulary.SPARKLINE_MAX_POINTS};

export const SAMPLE_MAX_BYTES = {vocabulary.SAMPLE_MAX_BYTES};

/** Whether a value names one of the element kinds this build draws. */
export function knownKind(value: unknown): value is ElementKind {{
  return (
    typeof value === "string" &&
    (ELEMENT_KINDS as readonly string[]).includes(value)
  );
}}
"""


def main(argv: list[str] | None = None) -> int:
    """Write the generated module, defaulting to the committed SPA path."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT,
                        help=f"target path (default: {DEFAULT_OUT.relative_to(REPO_ROOT)})")
    args = parser.parse_args(argv)
    text = render_typescript()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
